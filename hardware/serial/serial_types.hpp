#ifndef _SERIAL_TYPES_H_
#define _SERIAL_TYPES_H_

#include <chrono>
#include <cstdint>

// ============================================================================
// 飞镖视觉 —— 串口通信协议
//
// 接收：电控 -> 视觉，**单字节命令**（没有包头包尾）。
//   0 = 停止/待机
//   1 = 瞄准前哨站（两个最大目标中偏左的）
//   2 = 瞄准基地（两个最大目标中偏右的）
//   3 = 保持当前目标，重新粗对准（动作，只发一次，不要周期发）
//   视觉只接受 0~3，其它字节当噪声丢弃。
//   电控建议周期发送当前选择（例如 50~200ms 一次），切换目标最迟一个周期生效。
//
// 发送：视觉 -> 电控，固定 9 字节帧（见 DartSendPacket 和 04 文档）。
// ============================================================================

// 发送结构体：视觉 -> 电控
struct __attribute__((packed)) DartSendPacket
{
    uint8_t header = 0xBB;
    uint8_t found;          // 1 = 选中目标可见/已锁定
    uint8_t target;         // 0=无, 1=前哨站, 2=基地
    uint8_t state;          // 0=idle, 1=acquire(角度有效), 2=hold(电控保持不动)
    float   target_yaw_deg; // 云台需要转过的角度（度）；目标在右为正，hold 时恒 0
    uint8_t tail = 0x5B;
};

#endif // _SERIAL_TYPES_H_
